'use client';

import Link from 'next/link';
import { usePathname, useRouter } from 'next/navigation';
import { createClient } from '@/lib/supabase/client';

export default function Sidebar({ role = 'resident', user }) {
  const pathname = usePathname();
  const router = useRouter();
  const supabase = createClient();

  const residentLinks = [
    { href: '/resident/dashboard', label: 'Dashboard', icon: DashboardIcon },
    { href: '/resident/complaints/new', label: 'New Complaint', icon: PlusIcon },
    { href: '/resident/notices', label: 'Notices', icon: NoticeIcon },
  ];

  const adminLinks = [
    { href: '/admin/dashboard', label: 'Dashboard', icon: DashboardIcon },
    { href: '/admin/complaints', label: 'Complaints', icon: ListIcon },
    { href: '/admin/notices', label: 'Notices', icon: NoticeIcon },
    { href: '/admin/settings', label: 'Settings', icon: SettingsIcon },
  ];

  const links = role === 'admin' ? adminLinks : residentLinks;

  const handleLogout = async () => {
    await supabase.auth.signOut();
    router.push('/login');
    router.refresh();
  };

  return (
    <aside className="sidebar" id="sidebar">
      {/* Logo */}
      <div className="p-6 border-b border-border">
        <Link href={role === 'admin' ? '/admin/dashboard' : '/resident/dashboard'}>
          <h2 className="text-lg font-semibold tracking-tight text-text-primary">
            SMT
          </h2>
          <p className="text-[11px] font-medium tracking-widest uppercase text-text-muted mt-0.5">
            Maintenance Tracker
          </p>
        </Link>
      </div>

      {/* User Info */}
      <div className="px-6 py-4 border-b border-border">
        <p className="text-sm font-medium text-text-primary truncate">
          {user?.user_metadata?.full_name || 'User'}
        </p>
        <p className="text-[11px] uppercase tracking-widest text-text-muted mt-0.5">
          {role}
        </p>
      </div>

      {/* Navigation */}
      <nav className="flex-1 py-4">
        {links.map((link) => {
          const isActive = pathname === link.href || 
            (link.href !== '/admin/dashboard' && link.href !== '/resident/dashboard' && pathname.startsWith(link.href));
          return (
            <Link
              key={link.href}
              href={link.href}
              className={`sidebar-link ${isActive ? 'active' : ''}`}
            >
              <link.icon className="w-[18px] h-[18px]" />
              <span>{link.label}</span>
            </Link>
          );
        })}
      </nav>

      {/* Logout */}
      <div className="p-4 border-t border-border">
        <button
          onClick={handleLogout}
          className="sidebar-link w-full text-text-muted hover:text-status-overdue"
        >
          <LogoutIcon className="w-[18px] h-[18px]" />
          <span>Sign out</span>
        </button>
      </div>
    </aside>
  );
}

