-- 5. TRIGGER FUNCTIONS

-- Auto create profile & user_role on signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, full_name, apartment_no, phone)
  VALUES (
    NEW.id,
    COALESCE(NEW.raw_user_meta_data->>'full_name', 'Resident'),
    COALESCE(NEW.raw_user_meta_data->>'apartment_no', 'N/A'),
    COALESCE(NEW.raw_user_meta_data->>'phone', 'N/A')
  );

  INSERT INTO public.user_roles (user_id, role)
  VALUES (NEW.id, 'resident');

  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Auto-confirm user email upon registration
CREATE OR REPLACE FUNCTION public.auto_confirm_user()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.email_confirmed_at IS NULL THEN
    NEW.email_confirmed_at = NOW();
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created_auto_confirm
  BEFORE INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.auto_confirm_user();

-- Trigger function: Update timestamp on complaints
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER update_complaints_updated_at
  BEFORE UPDATE ON public.complaints
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER update_notices_updated_at
  BEFORE UPDATE ON public.notices
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Trigger function: Handle resolved_at timestamp
CREATE OR REPLACE FUNCTION public.handle_complaint_resolved_at()
RETURNS TRIGGER AS $$
BEGIN
  IF NEW.status = 'resolved' AND (OLD.status IS NULL OR OLD.status != 'resolved') THEN
    NEW.resolved_at = NOW();
    NEW.is_overdue = FALSE; -- Resolved items are never overdue
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_complaint_resolved_at
  BEFORE UPDATE ON public.complaints
  FOR EACH ROW EXECUTE FUNCTION public.handle_complaint_resolved_at();

-- Function: Overdue Checker (can be invoked by CRON or API trigger)
CREATE OR REPLACE FUNCTION public.check_overdue_complaints()
RETURNS VOID AS $$
DECLARE
  threshold_days INT := 7;
BEGIN
  SELECT COALESCE(value::INT, 7) INTO threshold_days
  FROM public.app_settings
  WHERE key = 'overdue_threshold_days';

  UPDATE public.complaints
  SET is_overdue = TRUE
  WHERE status IN ('open', 'in_progress')
    AND created_at < (NOW() - (threshold_days || ' days')::INTERVAL)
    AND is_overdue = FALSE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 6. CUSTOM ACCESS TOKEN HOOK FOR SUPABASE AUTH JWT
CREATE OR REPLACE FUNCTION public.custom_access_token_hook(event jsonb)
RETURNS jsonb AS $$
DECLARE
  claims jsonb;
  user_role public.app_role;
BEGIN
  SELECT role INTO user_role FROM public.user_roles
  WHERE user_id = (event->>'user_id')::uuid;

  claims := event->'claims';
  claims := jsonb_set(claims, '{user_role}', to_jsonb(COALESCE(user_role, 'resident')));
  event := jsonb_set(event, '{claims}', claims);
  RETURN event;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;

GRANT EXECUTE ON FUNCTION public.custom_access_token_hook TO supabase_auth_admin;
REVOKE EXECUTE ON FUNCTION public.custom_access_token_hook FROM authenticated, anon, public;

